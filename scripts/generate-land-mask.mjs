#!/usr/bin/env node
/**
 * Bakes the hero globe's continents into lib/globe/landMask.ts.
 *
 *   npm run globe:mask
 *
 * N points are spread evenly over the sphere with the shared Fibonacci
 * spiral (lib/globe/fibonacci.ts). Each is tested against Natural Earth land
 * (world-atlas, public domain) and recorded as one bit: land or sea. The
 * browser rebuilds positions from the same spiral, so it ships only the
 * bits — about 12.5 KB for 100,000 points — and never loads map geometry,
 * topojson or d3.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

import { geoBounds, geoContains } from "d3-geo";
import { feature } from "topojson-client";

const { fibonacciLonLat } = await import(
  new URL("../lib/globe/fibonacci.ts", import.meta.url)
);

const N = 100_000;
const SOURCE = "world-atlas/land-110m.json";

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve(SOURCE), "utf8"));
const land = feature(topology, topology.objects.land);

// One entry per polygon, with its bounding box, so each point is tested
// only against polygons that could contain it.
const polygons = land.features.flatMap((f) =>
  f.geometry.type === "MultiPolygon"
    ? f.geometry.coordinates.map((coordinates) => ({
        type: "Feature",
        geometry: { type: "Polygon", coordinates },
      }))
    : [f],
);
const candidates = polygons.map((p) => ({ p, b: geoBounds(p) }));

function inBounds([lon, lat], [[w, s], [e, n]]) {
  if (lat < s || lat > n) return false;
  // d3 reports antimeridian-crossing boxes with west > east.
  return w <= e ? lon >= w && lon <= e : lon >= w || lon <= e;
}

const started = Date.now();
const bits = new Uint8Array(Math.ceil(N / 8));
let landCount = 0;

for (let i = 0; i < N; i++) {
  const point = fibonacciLonLat(i, N);
  for (const { p, b } of candidates) {
    if (inBounds(point, b) && geoContains(p, point)) {
      bits[i >> 3] |= 1 << (i & 7);
      landCount++;
      break;
    }
  }
}

const base64 = Buffer.from(bits).toString("base64");

writeFileSync(
  new URL("../lib/globe/landMask.ts", import.meta.url),
  `/**
 * GENERATED by scripts/generate-land-mask.mjs — do not edit by hand.
 *
 * One bit per Fibonacci-sphere point (lib/globe/fibonacci.ts), set when the
 * point falls on land in Natural Earth ${SOURCE.split("/")[1]} (world-atlas;
 * Natural Earth data is public domain). Bit i is byte i >> 3, mask 1 << (i & 7).
 */

export const LAND_MASK = {
  points: ${N},
  landPoints: ${landCount},
  bits: "${base64}",
} as const;
`,
);

console.log(
  `${landCount} of ${N} points on land (${((landCount / N) * 100).toFixed(1)}%), ` +
    `${bits.length} bytes, ${((Date.now() - started) / 1000).toFixed(1)}s`,
);
